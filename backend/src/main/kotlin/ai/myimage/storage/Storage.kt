package ai.myimage.storage

import ai.myimage.config.AppProperties
import org.springframework.stereotype.Component
import java.io.ByteArrayInputStream
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.StandardOpenOption
import java.time.LocalDate
import java.time.ZoneOffset
import java.util.UUID
import javax.imageio.ImageIO

/** Where image bytes live. Metadata lives in PostgreSQL; bytes never do. Implement this for S3-compatible storage. */
interface ImageStorage {
    /** Stores bytes under a new unique key and returns the key. */
    fun save(bytes: ByteArray, extension: String): String

    /** @throws java.nio.file.NoSuchFileException if missing */
    fun read(key: String): ByteArray

    fun delete(key: String)
}

class LocalImageStorage(rootPath: Path) : ImageStorage {
    private val root: Path = rootPath.toAbsolutePath().normalize()
    private val keyPattern = Regex(
        "^\\d{4}/\\d{2}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\\.(png|jpg)$"
    )

    init {
        Files.createDirectories(root)
    }

    override fun save(bytes: ByteArray, extension: String): String {
        require(extension == "png" || extension == "jpg") { "unsupported extension" }
        val today = LocalDate.now(ZoneOffset.UTC)
        val key = "%04d/%02d/%s.%s".format(today.year, today.monthValue, UUID.randomUUID(), extension)
        val path = resolve(key)
        Files.createDirectories(path.parent)
        Files.write(path, bytes, StandardOpenOption.CREATE_NEW) // CREATE_NEW: never overwrite
        return key
    }

    override fun read(key: String): ByteArray = Files.readAllBytes(resolve(key))

    override fun delete(key: String) {
        Files.deleteIfExists(resolve(key))
    }

    /** Keys are generated by us, but are re-validated before touching the filesystem (defence against traversal). */
    private fun resolve(key: String): Path {
        require(keyPattern.matches(key)) { "invalid storage key" }
        val path = root.resolve(key).normalize()
        require(path.startsWith(root)) { "invalid storage key" }
        return path
    }
}

class ImageRejectedException(message: String) : RuntimeException(message)

data class ValidatedImage(val mimeType: String, val extension: String, val width: Int, val height: Int, val sizeBytes: Long)

/** Checks bytes returned by a model before they are stored: real PNG/JPEG, size and dimension limits. */
@Component
class ImageValidator(private val props: AppProperties) {
    private val pngMagic = byteArrayOf(0x89.toByte(), 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A)
    private val jpegMagic = byteArrayOf(0xFF.toByte(), 0xD8.toByte(), 0xFF.toByte())

    private fun startsWith(bytes: ByteArray, magic: ByteArray) =
        bytes.size >= magic.size && magic.indices.all { bytes[it] == magic[it] }

    fun validate(bytes: ByteArray, declaredMime: String?): ValidatedImage {
        if (bytes.isEmpty()) throw ImageRejectedException("empty image")
        if (bytes.size > props.storage.maxImageBytes) throw ImageRejectedException("image exceeds size limit")
        val (mime, ext) = when {
            startsWith(bytes, pngMagic) -> "image/png" to "png"
            startsWith(bytes, jpegMagic) -> "image/jpeg" to "jpg"
            else -> throw ImageRejectedException("unsupported image type (only PNG and JPEG are accepted)")
        }
        if (declaredMime != null && declaredMime != mime) throw ImageRejectedException("declared MIME type does not match content")

        var w = 0
        var h = 0
        ImageIO.createImageInputStream(ByteArrayInputStream(bytes)).use { iis ->
            val readers = ImageIO.getImageReaders(iis)
            if (!readers.hasNext()) throw ImageRejectedException("unreadable image")
            val reader = readers.next()
            try {
                reader.setInput(iis)
                w = reader.getWidth(0)
                h = reader.getHeight(0)
            } catch (e: Exception) {
                throw ImageRejectedException("unreadable image")
            } finally {
                reader.dispose()
            }
        }
        if (w <= 0 || h <= 0 || w > props.storage.maxImageWidth || h > props.storage.maxImageHeight) {
            throw ImageRejectedException("image dimensions out of range")
        }
        return ValidatedImage(mime, ext, w, h, bytes.size.toLong())
    }
}
